// uniqueViolationCode is the PostgreSQL SQLSTATE for a unique
// constraint violation.
const uniqueViolationCode = "23505"

// mapError translates backend errors into the sentinel errors of the
// auth package so the service layer can react uniformly:
//
//   - pgx.ErrNoRows (possibly wrapped) maps to auth.ErrNotFound.
//   - *pgconn.PgError with SQLSTATE 23505 (possibly wrapped) maps to
//     auth.ErrDuplicate.
//
// Any other error, including nil, is returned unchanged; mapError never
// wraps foreign errors with additional context, so errors.Is keeps
// working for context.Canceled, context.DeadlineExceeded and
// *pgconn.PgError.
func mapError(err error) error {
	if err == nil {
		return nil
	}
	if errors.Is(err, pgx.ErrNoRows) {
		return auth.ErrNotFound
	}
	var pgErr *pgconn.PgError
	if errors.As(err, &pgErr) && pgErr.Code == uniqueViolationCode {
		return auth.ErrDuplicate
	}
	return err
}

// newID returns a random, UUIDv4-formatted identifier such as
// "3b241101-e2bb-4255-8caf-4136c566a962". It is used to populate the ID
// field of records created through the store. The randomness comes from
// crypto/rand; the generator panics only if the system CSPRNG fails,
// which in practice means the host is unusable.
func newID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(fmt.Sprintf("pgstore: newID: crypto/rand failed: %v", err))
	}
	// Set the UUID version 4 and RFC 4122 variant bits.
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

// defaultListLimit is the page size applied when ListOptions.Limit is
// zero or negative.
const defaultListLimit = 100

// normalizeListOptions clamps ListOptions for use in SQL LIMIT/OFFSET
// clauses:
//
//   - Limit <= 0 becomes defaultListLimit (100). Zero means "store
//     default" per the auth.Store contract; negative limits are treated
//     the same way instead of erroring.
//   - Offset < 0 becomes 0; a negative offset would be a SQL error.
//
// Large limits are not capped.
func normalizeListOptions(opts auth.ListOptions) (limit, offset int) {
	limit = opts.Limit
	if limit <= 0 {
		limit = defaultListLimit
	}
	offset = opts.Offset
	if offset < 0 {
		offset = 0
	}
	return limit, offset
}

// nowUTC returns the current time in UTC truncated to microsecond
// precision, matching the resolution of PostgreSQL timestamptz columns
// so timestamps generated by the store round-trip exactly.
func nowUTC() time.Time {
	return time.Now().UTC().Truncate(time.Microsecond)
}

// normalizeTime converts t to UTC and truncates it to microsecond
// precision, the resolution of PostgreSQL timestamptz. Truncation (not
// rounding) keeps the order of any two instants: a.Before(b) never
// turns into b.Before(a), so comparisons the service makes between
// stored timestamps (for example a token's CreatedAt against the
// user's CreatedAt) behave exactly as they did on the in-memory
// values. The zero time stays zero.
func normalizeTime(t time.Time) time.Time {
	if t.IsZero() {
		return t
	}
	return t.UTC().Truncate(time.Microsecond)
}

// normalizeTimePtr is normalizeTime for optional timestamps; nil stays
// nil.
func normalizeTimePtr(t *time.Time) *time.Time {
	if t == nil {
		return nil
	}
	normalized := normalizeTime(*t)
	return &normalized
}

// utcOrNow returns t normalized like normalizeTime, substituting now
// when t is zero. It backs the "populate timestamps on create"
// contract.
func utcOrNow(t, now time.Time) time.Time {
	if t.IsZero() {
		return now
	}
	return normalizeTime(t)
}

// toUTC converts a timestamp read from PostgreSQL to UTC. pgx returns
// timestamptz values in the local time zone of the process; converting
// them keeps the records returned by the store independent of the
// host configuration.
func toUTC(t *time.Time) {
	*t = t.UTC()
}

// expiryCutoff converts the "before" instant of a bulk expiry delete
// into the bound sent to PostgreSQL. Stored timestamps are whole
// microseconds, and for such a value v, v < before holds exactly when
// v < before rounded UP to the next whole microsecond. Rounding up
// therefore keeps "strictly before" exact even when before carries
// nanoseconds (pgx itself would truncate them, which could keep an
// expired row alive).
func expiryCutoff(before time.Time) time.Time {
	before = before.UTC()
	truncated := before.Truncate(time.Microsecond)
	if truncated.Equal(before) {
		return truncated
	}
	return truncated.Add(time.Microsecond)
}
